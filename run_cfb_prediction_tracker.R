if (length(commandArgs(trailingOnly = TRUE))) stop("This locked experiment takes no arguments.")
script <- grep("^--file=", commandArgs(), value = TRUE)
project <- if (length(script)) dirname(normalizePath(sub("^--file=", "", script[1]), winslash = "/")) else getwd()
for (file in c("config.R", "store.R", "features.R", "coaches.R", "adapters.R", "models.R",
  "coach_migration.R", "historical_data.R", "preseason.R", "bridge.R", "workflow.R"))
  source(file.path(project, "cfb_v2", file))
for (file in c("controlled_ats.R", "four_way.R", "external_ratings.R", "external_backtest.R", "prediction_tracker.R"))
  source(file.path(project, "cfb_v3/experiments", file))
result <- run_prediction_tracker(project)
print(result$summary, row.names = FALSE)
cat("Prediction Tracker challenger report:", file.path(result$output, "REPORT.md"), "\n")
