args <- commandArgs(trailingOnly=TRUE)
stopifnot(length(args)==2L)
cap <- as.numeric(args[1]); stopifnot(cap %in% c(24,25,35,42))
out <- normalizePath(args[2],winslash="/",mustWork=TRUE)
for(module in c("config","store","features","coaches","adapters","models",
  "coach_migration","historical_data","preseason","bridge","workflow","live_data"))
  source(file.path("cfb_v2",paste0(module,".R")))
source("cfb_v3/experiments/margin_cap_features.R")
config <- cfb_v2_config(getwd(),2026L)
path <- file.path(out,paste0("cap_",cap,".rds"))
if(file.exists(path)) stop("Refusing to overwrite completed cap worker.")
cat("Building cap",cap,"\n"); flush.console()
cache <- margin_cap_load_inputs(config)
result <- margin_cap_build(config,cap,cache)
stopifnot(identical(cache$source_md5,tools::md5sum(cache$source_paths)))
saveRDS(result,paste0(path,".partial"))
stopifnot(file.rename(paste0(path,".partial"),path))
cat("Prepared cap",cap,":",path,"\n")
